package Hampouch.server.domain.challenge.service;

/**
 * 조회 기간에 걸친 진행 중 챌린지의 상태. 지출 분석 마지막 문장을 고르는 데만 쓴다.
 * boolean 두 개(겹침 / 페이스 지킴)로 두지 않는 이유는 "안 겹치는데 페이스는 지킴" 같은 없는 상태가
 * 표현 가능해지기 때문 — 셋 중 하나라는 사실 자체를 타입으로 못박는다.
 */
public enum ChallengeProgress {

    /**
     * 겹치는 진행 중 챌린지가 없거나, 있어도 아직 시작 전이라 할 말이 없음.
     * 마지막 문장은 챌린지와 무관한 기존 규칙으로 간다.
     */
    NONE,

    /** 경과일만큼의 예산 안에서 쓰는 중. */
    ON_TRACK,

    /** 경과일만큼의 예산을 이미 넘김. 남은 기간을 이 페이스로 가면 예산을 못 지킨다. */
    OVER_PACE
}
